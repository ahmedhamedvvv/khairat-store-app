/// Past orders so the merchant dashboard and "My orders" have something on day one.
List<Order> seedOrders(DateTime now) {
  Order make(String id, int daysAgo, List<(String, int, int)> items, OrderStatus reached, PaymentMethod pay) {
    final created = now.subtract(Duration(days: daysAgo, hours: 3 + daysAgo % 5));
    final lines = [
      for (final (pid, vi, q) in items)
        () {
          final p = seedProducts.firstWhere((p) => p.id == pid);
          final v = p.variants[vi];
          return OrderLine(productId: pid, variantId: v.id, name: p.name, variantLabel: v.label, unitPrice: v.price, qty: q);
        }(),
    ];
    final sub = lines.fold<double>(0, (s, l) => s + l.total);
    final ship = sub >= 300 ? 0.0 : 20.0;
    final total = sub + ship;
    final hist = <OrderStatus, DateTime>{};
    if (reached == OrderStatus.cancelled) {
      hist[OrderStatus.placed] = created;
      hist[OrderStatus.cancelled] = created.add(const Duration(hours: 2));
    } else {
      const flow = [OrderStatus.placed, OrderStatus.confirmed, OrderStatus.preparing, OrderStatus.shipped, OrderStatus.delivered];
      for (var i = 0; i <= flow.indexOf(reached); i++) {
        hist[flow[i]] = created.add(Duration(hours: i * 7));
      }
    }
    return Order(
      id: id,
      createdAt: created,
      lines: lines,
      address: demoAddress,
      payment: pay,
      slot: DeliverySlot.standard,
      subtotal: sub,
      discount: 0,
      shipping: ship,
      giftWrap: 0,
      total: total,
      vat: total - total / 1.15,
      vatRate: 0.15,
      history: hist,
      rated: daysAgo > 4,
    );
  }

  return [
